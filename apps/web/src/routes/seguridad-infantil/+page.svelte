	<p>
		Caigo tiene <b>tolerancia cero</b> con la explotación y el abuso sexual de niñas, niños y adolescentes
		(CSAE), y con cualquier material de abuso sexual infantil (CSAM). Estos son los estándares que aplicamos
		en la app de Caigo para iPhone y Android y en caigo.com.ar.
	</p>

	<h2>1. Solo para mayores de 18</h2>
	<p>
		Caigo es solo para personas de 18 años o más. Pedimos la fecha de nacimiento al crear la cuenta
		y una selfie para verificar que la persona es real, y el equipo puede pedir el DNI. Si sabemos o
		sospechamos que una cuenta es de alguien menor de 18, la suspendemos.
	</p>

	<h2>2. Qué está prohibido</h2>
	<ul>
		<li>
			Publicar, pedir, compartir o promocionar material de abuso sexual infantil, por cualquier
			medio.
		</li>
		<li>
			Contactar a una persona menor de edad con fines sexuales (grooming) o intentar encontrarse con
			ella.
		</li>
		<li>Sexualizar a niñas, niños o adolescentes en fotos, textos, perfiles, planes o mensajes.</li>
		<li>Usar Caigo para la trata o la explotación de personas menores de edad.</li>
	</ul>

	<h2>3. Cómo denunciar</h2>
	<p>
		Desde la app, en el perfil de una persona o en un plan, tocá <b>Reportar</b>, elegí «Inseguro» o
		«Inapropiado» y contanos qué pasó. También podés escribirnos a
		<a href="mailto:seguridad@caigo.com.ar">seguridad@caigo.com.ar</a>. Si alguien está en peligro
		ahora, llamá al&nbsp;911.
	</p>

	<h2>4. Qué hacemos con cada denuncia</h2>
	<ul>
		<li>La revisamos lo antes posible y quitamos el contenido que infringe estas reglas.</li>
		<li>Suspendemos la cuenta y bloqueamos que vuelva con el mismo mail o DNI.</li>
		<li>
			Conservamos la información necesaria y la denunciamos ante las autoridades argentinas (Unidad
			Fiscal Especializada en Ciberdelincuencia del Ministerio Público Fiscal) y, cuando
			corresponde, ante el NCMEC (CyberTipline).
		</li>
		<li>Colaboramos con los pedidos de la justicia y de las fuerzas de seguridad.</li>
	</ul>

	<h2>5. Leyes que cumplimos</h2>
	<p>
		Cumplimos la Ley 26.904 (grooming), el artículo 128 del Código Penal y las demás normas
		argentinas de protección de niñas, niños y adolescentes, además de las políticas de Google Play
		y de la App Store.
	</p>

